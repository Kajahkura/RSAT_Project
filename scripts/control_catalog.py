"""Generate trusted public workspace labels from RSAT's original controls."""

import argparse
import json
from pathlib import Path

from rsat.ai_security import evaluate_ai

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    controls = json.loads((ROOT / "src/rsat/policies/core.json").read_text())["rules"]
    controls += evaluate_ai([])
    labels = {c["id"]: {"title": c["title"], "remediation": c["remediation"]} for c in controls}
    source = (
        "// Generated by scripts/control_catalog.py from public RSAT controls.\n"
        "export const publicControls:Record<string,{title:string;remediation:string}> = "
        + json.dumps(labels, ensure_ascii=False, indent=2) + ";\n"
    )
    target = ROOT / "web/src/control-catalog.ts"
    if args.check:
        if target.read_text() != source:
            raise SystemExit("Regenerate the public control catalog with python scripts/control_catalog.py")
    else:
        target.write_text(source)


if __name__ == "__main__":
    main()
